/**
 * Teamwork Graph relationship types usable as Cypher labels, with the object types each end
 * accepts. Generated from the public catalog at
 * https://developer.atlassian.com/platform/teamwork-graph/api-reference/relationship-types/
 * (Oct 2026). \`content_entity_links_entity\` has no enumerable target side (any resolvable
 * entity), so it is only traversed outward.
 */
export type RelationshipKind = "canonical" | "logical" | "activity";

export interface RelationshipType {
  /** Cypher label and the name reported by the MCP, e.g. \`atlassian_user_owns_confluence_page\`. */
  readonly name: string;
  readonly kind: RelationshipKind;
  /** Object types allowed on the source (outgoing) side. */
  readonly from: readonly string[];
  /** Object types allowed on the target (incoming) side; empty when unbounded. */
  readonly to: readonly string[];
}

function rel(
  name: string,
  kind: RelationshipKind,
  from: readonly string[],
  to: readonly string[],
): RelationshipType {
  return { name, kind, from, to };
}

